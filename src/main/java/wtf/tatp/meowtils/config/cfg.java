    public static void initFile(File file) {
        configFile = file;
    }

    public static void load() {
        if (configFile == null) {
            throw new IllegalStateException("Config file not set!");
        }
        if (configFile.exists()) {
            try (FileReader reader = new FileReader(configFile);){
                v = gson.fromJson((Reader)reader, cfg.class);
                if (v == null) {
                    v = new cfg();
                }
            }
            catch (IOException e) {
                e.printStackTrace();
                v = new cfg();
            }
        } else {
            v = new cfg();
            cfg.save();
        }
    }

    public static void save() {
        if (configFile == null) {
            return;
        }
        try (FileWriter writer = new FileWriter(configFile);){
            gson.toJson((Object)v, (Appendable)writer);
        }
        catch (IOException e) {
            e.printStackTrace();
        }
    }

